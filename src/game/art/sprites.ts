/** Frame order per facing: idle, step A, idle, step B. */
export function agentFrames(facing: Facing): Pixels[] {
  if (facing === 'side') {
    const f = (legs: string[]) => [...HEAD_SIDE, ...BODY_SIDE, ...legs];
    return [f(LEGS_SIDE.idle), f(LEGS_SIDE.a), f(LEGS_SIDE.idle), f(LEGS_SIDE.a)];
  }
  const head = facing === 'down' ? HEAD_FRONT : HEAD_BACK;
  const f = (legs: string[]) => [...head, ...BODY_FRONT, ...legs];
  return [f(LEGS_FRONT.idle), f(LEGS_FRONT.a), f(LEGS_FRONT.idle), f(LEGS_FRONT.b)];
}

